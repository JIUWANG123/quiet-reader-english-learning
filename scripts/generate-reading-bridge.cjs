const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/features/reader/readingBridge.ts'), 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions: {target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS}}).outputText;
const script = `(function(){var exports={};${compiled}\nexports.readingBridge();})();true;`;
const output = '// Generated by scripts/generate-reading-bridge.cjs; do not edit.\nexport const readingBridgeScript = ' + JSON.stringify(script) + ';\n';
const target = path.join(root, 'src/features/reader/readingBridge.generated.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Reading bridge is stale; run npm run generate:reader');
} else fs.writeFileSync(target, output);
